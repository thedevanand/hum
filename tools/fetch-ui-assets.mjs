// Downloads the UI font into fonts/ and builds js/icons.js from Phosphor Icons.
// Run from the project root: node tools/fetch-ui-assets.mjs
import { mkdir, writeFile } from 'node:fs/promises';

// SIL Open Font License, served by Fontsource
const FONT = 'https://cdn.jsdelivr.net/fontsource/fonts/';
const FONTS = {
  'geist-mono.woff2': 'geist-mono:vf@latest/latin-wght-normal.woff2',
};

// MIT, Phosphor Icons. name in the app → [phosphor name, weight]
const PH = 'https://cdn.jsdelivr.net/npm/@phosphor-icons/core@2.1.1/assets/';
const ICONS = {
  play: ['play', 'fill'], pause: ['pause', 'fill'], stop: ['stop', 'fill'], rewind: ['skip-back', 'fill'],
  undo: ['arrow-counter-clockwise', 'bold'], redo: ['arrow-clockwise', 'bold'],
  plus: ['plus', 'bold'], minus: ['minus', 'bold'], x: ['x', 'bold'], trash: ['trash', 'bold'], copy: ['copy', 'bold'],
  split: ['scissors', 'bold'], crop: ['crop', 'bold'], fit: ['arrows-out-line-horizontal', 'bold'], rev: ['swap', 'bold'],
  upload: ['upload-simple', 'bold'], export: ['export', 'bold'], search: ['magnifying-glass', 'bold'],
  vol: ['speaker-high', 'fill'], mic: ['microphone', 'fill'], tempo: ['metronome', 'bold'], key: ['music-note-simple', 'fill'],
  drums: ['squares-four', 'fill'], piano: ['piano-keys', 'fill'], flute: ['music-notes', 'fill'], synth: ['wave-sawtooth', 'bold'],
  audio: ['waveform', 'bold'], gear: ['gear', 'bold'], repeat: ['repeat', 'bold'], tune: ['magic-wand', 'fill'], file: ['file-plus', 'bold'],
  sine: ['wave-sine', 'bold'], triangle: ['wave-triangle', 'bold'], sawtooth: ['wave-sawtooth', 'bold'], square: ['wave-square', 'bold'],
};

const get = async url => { const r = await fetch(url); if (!r.ok) throw new Error(`${r.status} ${url}`); return r; };

await mkdir('fonts', { recursive: true });
for (const [file, path] of Object.entries(FONTS)) await writeFile(`fonts/${file}`, Buffer.from(await (await get(FONT + path)).arrayBuffer()));

const out = {};
await Promise.all(Object.entries(ICONS).map(async ([name, [ph, weight]]) => {
  const svg = await (await get(`${PH}${weight}/${ph}${weight === 'regular' ? '' : '-' + weight}.svg`)).text();
  out[name] = svg.replace(/ xmlns="[^"]+"/, '').replace('<svg ', '<svg aria-hidden="true" ').trim();
}));
await writeFile('js/icons.js', `// Generated by tools/fetch-ui-assets.mjs from Phosphor Icons (MIT). Do not edit by hand.\nexport const ICON = ${JSON.stringify(out, Object.keys(ICONS), 1)};\n`);
console.log(`${Object.keys(FONTS).length} fonts, ${Object.keys(out).length} icons`);
